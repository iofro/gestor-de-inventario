    def _apply_quick_range(self):
        if not self.date_filter_cb.isChecked():
            return
        option = self.quick_range.currentText()
        today = date.today()
        if option == "Hoy":
            self.date_from.setDate(QDate(today))
            self.date_to.setDate(QDate(today))
            self.date_from.setEnabled(False)
            self.date_to.setEnabled(False)
        elif option == "Esta semana":
            start = today - timedelta(days=today.weekday())
            end = start + timedelta(days=6)
            self.date_from.setDate(QDate(start))
            self.date_to.setDate(QDate(end))
            self.date_from.setEnabled(False)
            self.date_to.setEnabled(False)
        elif option == "Este mes":
            start = today.replace(day=1)
            if today.month == 12:
                end = date(today.year, 12, 31)
            else:
                end = date(today.year, today.month + 1, 1) - timedelta(days=1)
            self.date_from.setDate(QDate(start))
            self.date_to.setDate(QDate(end))
            self.date_from.setEnabled(False)
            self.date_to.setEnabled(False)
        elif option == "Este año":
            start = date(today.year, 1, 1)
            end = date(today.year, 12, 31)
            self.date_from.setDate(QDate(start))
            self.date_to.setDate(QDate(end))
            self.date_from.setEnabled(False)
            self.date_to.setEnabled(False)
        else:  # Personalizado
            self.date_from.setEnabled(True)
            self.date_to.setEnabled(True)
        self.load_invoices()

    def refresh_filters(self):
        """Update client and vendor filter combos with latest data."""
        self.client_filter.blockSignals(True)
        self.vendedor_filter.blockSignals(True)

        current_client = self.client_filter.currentData()
        current_vend = self.vendedor_filter.currentData()

        self.client_filter.clear()
        self.client_filter.addItem("Todos", None)
        for c in self.manager._clientes:
            self.client_filter.addItem(c.get("nombre", ""), c.get("id"))

        self.vendedor_filter.clear()
        self.vendedor_filter.addItem("Todos", None)
        for v in self.manager.db.get_trabajadores(solo_vendedores=True):
            self.vendedor_filter.addItem(v.get("nombre", ""), v.get("id"))

        def _restore(combo, value):
            if value is None:
                combo.setCurrentIndex(0)
                return
            for i in range(combo.count()):
                if combo.itemData(i) == value:
                    combo.setCurrentIndex(i)
                    return
            combo.setCurrentIndex(0)

        _restore(self.client_filter, current_client)
        _restore(self.vendedor_filter, current_vend)

        self.client_filter.blockSignals(False)
        self.vendedor_filter.blockSignals(False)

    @staticmethod
    def _map_envio_state(state):
        est = str(state).lower()
        if est == "aceptado":
            return "Aceptado"
        if est == "rechazado":
            return "Rechazado"
        if est == "error":
            return "Error"
        if est in {"transmitido", "recibido", "procesado"}:
            return "Enviado"
        return "Pendiente"

    @classmethod
    def _detectar_estado_factura(
        cls,
        venta,
        pdf_path=None,
        json_path=None,
        cur=None,
        *,
        venta_id=None,
        numero_control=None,
        codigo_generacion=None,
        doc_tipo=None,
    ):
        """Determine ``estado`` and ``envio`` for an invoice.

        Parameters mirror the data available from the database and the
        filesystem so the same logic can be reused from different
        codepaths.
        """

        pdf_exists = bool(pdf_path and os.path.exists(pdf_path))
        json_exists = bool(json_path and os.path.exists(json_path))

        tipo_lower = str(doc_tipo or "").strip().lower()
        is_nota = tipo_lower.startswith("nota")

        if venta:
            estado = "Completa" if pdf_exists and json_exists else "Incompleta"
        else:
            if is_nota:
                estado = "Completa" if pdf_exists and json_exists else "Incompleta"
            else:
                estado = "Sin venta" if pdf_exists and json_exists else "Incompleta"

        envio = "Pendiente de envío"
        env_row = None
        try:
            if cur is not None:
                if venta_id is not None:
                    success = cur.execute(
                        """
                        SELECT estado FROM dte_envios
                        WHERE venta_id=? AND estado IN (?, ?, ?, ?)
                        ORDER BY id DESC LIMIT 1
                        """,
                        (
                            venta_id,
                            "Transmitido",
                            "Recibido",
                            "Procesado",
                            "Aceptado",
                        ),
                    ).fetchone()
                    if success:
                        env_row = success
                    else:
                        env_row = cur.execute(
                            "SELECT estado FROM dte_envios WHERE venta_id=? ORDER BY id DESC LIMIT 1",
                            (venta_id,),
                        ).fetchone()
                elif codigo_generacion or numero_control:
                    query_success = (
                        "SELECT estado FROM dte_envios WHERE venta_id IS NULL AND respuesta LIKE ? AND estado IN (?, ?, ?, ?) ORDER BY id DESC LIMIT 1"
                    )
                    query_latest = (
                        "SELECT estado FROM dte_envios WHERE venta_id IS NULL AND respuesta LIKE ? ORDER BY id DESC LIMIT 1"
                    )
                    if codigo_generacion:
                        env_row = cur.execute(
                            query_success,
                            (
                                f"%{codigo_generacion}%",
                                "Transmitido",
                                "Recibido",
                                "Procesado",
                                "Aceptado",
                            ),
                        ).fetchone()
                        if not env_row:
                            env_row = cur.execute(
                                query_latest,
                                (f"%{codigo_generacion}%",),
                            ).fetchone()
                    if not env_row and numero_control:
                        env_row = cur.execute(
                            query_success,
                            (
                                f"%{numero_control}%",
                                "Transmitido",
                                "Recibido",
                                "Procesado",
                                "Aceptado",
                            ),
                        ).fetchone()
                        if not env_row:
                            env_row = cur.execute(
                                query_latest,
                                (f"%{numero_control}%",),
                            ).fetchone()
        except Exception:
            env_row = None
        if env_row:
            envio = cls._map_envio_state(env_row["estado"])

        return estado, envio

    def _get_invoices_from_db(self):
        """Return invoice entries stored in the database.

        Unlike the previous implementation, records are no longer
        deleted when their corresponding sale or files are missing. Such
        entries are kept and flagged through the ``estado`` field so they
        can be inspected from the UI. Additionally, the transmission
        state stored in ``dte_envios`` is exposed via the ``envio`` key.
        """

        cur = self.manager.db.cursor
        cur.execute(
            "SELECT id, venta_id, tipo, ruta, fecha_creacion FROM facturas_pdf"
        )
        records = cur.fetchall()
        rows = []
        for rec in records:
            try:
                doc_tipo = rec["tipo"]
            except (KeyError, IndexError):
                doc_tipo = None
            tipo_lower = str(doc_tipo or "").strip().lower()
            venta = None
            if rec["venta_id"] is not None and not tipo_lower.startswith("nota"):
                venta = self.manager.db.get_venta_by_id(rec["venta_id"])
            ruta = rec["ruta"]
            json_path = os.path.splitext(ruta)[0] + ".json" if ruta else None

            fecha_creacion = rec["fecha_creacion"] or ""
            fdate = None
            if fecha_creacion:
                try:
                    fdate = datetime.strptime(fecha_creacion, "%Y-%m-%d %H:%M:%S")
                except Exception:
                    fdate = None
            fecha_str = fdate.strftime("%Y-%m-%d %H:%M") if fdate else fecha_creacion

            row_type = "venta"
            cliente_nombre = ""
            total = None
            numero_control = None
            codigo_generacion = None
            if venta:
                getter = getattr(self.manager.db, "get_cliente", None)
                if venta.get("cliente_id") and getter:
                    try:
                        cliente = getter(venta.get("cliente_id"))
                        cliente_nombre = cliente.get("nombre", "") if cliente else ""
                    except Exception:
                        cliente_nombre = ""
                total = venta.get("total")
                row_type = "ticket" if self._is_ticket_sale(venta) else "venta"
            else:
                row_type = "orphan"
                if json_path and os.path.exists(json_path):
                    try:
                        with open(json_path, "r", encoding="utf-8") as fh:
                            data = json.load(fh)
                        ident = data.get("identificacion", {})
                        numero_control = ident.get("numeroControl")
                        codigo_generacion = ident.get("codigoGeneracion")
                    except Exception:
                        numero_control = None
                        codigo_generacion = None

            estado, envio = self._detectar_estado_factura(
                venta,
                ruta,
                json_path,
                cur,
                venta_id=rec["venta_id"],
                numero_control=numero_control,
                codigo_generacion=codigo_generacion,
                doc_tipo=doc_tipo,
            )

            row = {
                "row_type": row_type,
                "id": rec["id"],
                "venta_id": rec["venta_id"],
                "name": os.path.splitext(os.path.basename(ruta or ""))[0],
                "fecha": fecha_str,
                "_parsed_fecha": fdate,
                "cliente": cliente_nombre,
                "total": total,
                "estado": estado,
                "envio": envio,
                "tipo": doc_tipo,
            }
            if row_type == "orphan":
                row["pdf"] = ruta
                row["json"] = json_path
            rows.append(row)
        return rows

